"""Manufacturing package for MAO_MAIN A0 (KiCad 10 python + kicad-cli). Run after the final DRC.

Writes hardware/mao/outputs/fab/:
  gerbers/                F.Cu, In1.Cu, In2.Cu, B.Cu, paste, silk (mask subtracted), mask, Edge.Cuts, Gerber X2,
                          plus the .gbrjob (4 layers, 1.6 mm, JLC04161H-1080)
  drill/                  Excellon, plated and non-plated holes separate, Gerber X2 drill maps
  MAO_MAIN_A0-gerbers.zip gerbers/ and drill/ together, for upload
  CPL-MAO_MAIN_A0.csv     KiCad placement, both sides, mm, DNP and board-only items left out
  CPL-MAO_MAIN_A0-JLC.csv the same rows under JLC's column names (Designator, Mid X, Mid Y, Layer, Rotation)
  BOM-MAO_MAIN_A0-JLC.csv one line per (LCSC, footprint): Comment (the value, or the MPN where one part serves
                          several functions, e.g. the two touch springs), Designator, Footprint, LCSC Part #,
                          Manufacturer Part, Manufacturer; DNP and excluded-from-BOM parts left out
  ASSEMBLY-MAO_MAIN_A0-top.pdf / -bottom.pdf
                          assembly drawing at 2.5:1: Fab outlines, sketched pads, every reference (mao_labels.py puts
                          one on Fab for each part), DNP crossed out; bottom mirrored as seen from below
  FAB-NOTES.txt           order options and assembly notes that travel with the files (ODD JOBS 178)
The board file is read, never saved. Every BOM line must carry an LCSC number (asserted).
"""
