def cli(*args):
    r = subprocess.run([str(CLI), *map(str, args)], capture_output=True, text=True)
    assert r.returncode == 0, (args, r.stdout, r.stderr)


def field(f, name):
    for fl in f.GetFields():
        if fl.GetName() == name:
            return fl.GetText()
    return ''


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / 'gerbers').mkdir(parents=True)
    (OUT / 'drill').mkdir()
    cli('pcb', 'export', 'gerbers', '--layers', LAYERS, '--subtract-soldermask', '-o', OUT / 'gerbers', TARGET)
    cli('pcb', 'export', 'drill', '--format', 'excellon', '--excellon-separate-th', '--generate-map',
        '--map-format', 'gerberx2', '-u', 'mm', '-o', OUT / 'drill', TARGET)
    for side, layers, extra in (('top', 'F.Fab,Edge.Cuts', []), ('bottom', 'B.Fab,Edge.Cuts', ['--mirror'])):
        cli('pcb', 'export', 'pdf', '--mode-single', '--layers', layers, *extra, '--sketch-pads-on-fab-layers',
            '--crossout-DNP-footprints-on-fab-layers', '--include-border-title', '--black-and-white', '--scale', '2.5',
            '-o', OUT / ('ASSEMBLY-%s-%s.pdf' % (NAME, side)), TARGET)
    cpl = OUT / ('CPL-%s.csv' % NAME)
    cli('pcb', 'export', 'pos', '--side', 'both', '--format', 'csv', '--units', 'mm', '--exclude-dnp', '-o', cpl, TARGET)

    b = pcb.LoadBoard(str(TARGET))
    fps = {f.GetReference(): f for f in b.GetFootprints()}
    skip = {r for r, f in fps.items() if f.IsExcludedFromBOM() or f.IsBoardOnly() or f.IsDNP()
            or r.startswith(('FID', 'TP', 'H'))}
    rows = [r for r in csv.DictReader(open(cpl)) if r['Ref'] not in skip]
    with open(cpl, 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=['Ref', 'Val', 'Package', 'PosX', 'PosY', 'Rot', 'Side'])
        w.writeheader()
        w.writerows(rows)
    with open(OUT / ('CPL-%s-JLC.csv' % NAME), 'w', newline='') as fh:
        w = csv.writer(fh)
        w.writerow(['Designator', 'Mid X', 'Mid Y', 'Layer', 'Rotation'])
        for r in rows:
            w.writerow([r['Ref'], r['PosX'] + 'mm', r['PosY'] + 'mm', 'Top' if r['Side'] == 'top' else 'Bottom', r['Rot']])
    with zipfile.ZipFile(OUT / ('%s-gerbers.zip' % NAME), 'w', zipfile.ZIP_DEFLATED) as z:
        for p in sorted((OUT / 'gerbers').iterdir()) + sorted((OUT / 'drill').iterdir()):
            z.write(p, p.name)

    lines = OrderedDict()
    for ref in sorted(fps, key=lambda r: (''.join(c for c in r if c.isalpha()), int(''.join(c for c in r if c.isdigit()) or 0))):
        f = fps[ref]
        if ref in skip:
            continue
        lcsc = field(f, 'LCSC')
        assert lcsc, ('BOM part without an LCSC number', ref)
        key = (lcsc, str(f.GetFPID().GetLibItemName()))
        line = lines.setdefault(key, {'refs': [], 'values': [], 'mpn': field(f, 'MPN'), 'mfr': field(f, 'Manufacturer')})
        assert line['mpn'] == field(f, 'MPN'), ('one LCSC number, two MPNs', ref)
        line['refs'].append(ref)
        line['values'].append(f.GetValue())
    with open(OUT / ('BOM-%s-JLC.csv' % NAME), 'w', newline='') as fh:
        w = csv.writer(fh)
        w.writerow(['Comment', 'Designator', 'Footprint', 'LCSC Part #', 'Manufacturer Part', 'Manufacturer', 'Quantity'])
        for (lcsc, fp), line in lines.items():
            value = line['values'][0] if len(set(line['values'])) == 1 else line['mpn']
            w.writerow([value, ','.join(line['refs']), fp, lcsc, line['mpn'], line['mfr'], len(line['refs'])])
    vias = [t for t in b.GetTracks() if isinstance(t, pcb.PCB_VIA)]
    n_th = sum(1 for f in fps.values() for p in f.Pads()
               if p.GetAttribute() == pcb.PAD_ATTRIB_PTH and p.GetDrillSize().x < pcb.FromMM(0.25))
    lab_json = OUTPUTS / 'ASSEMBLY-LABELS.json'
    unplaced = json.loads(lab_json.read_text()).get('without_silk_spot', []) if lab_json.exists() else []
    tabs_json = OUTPUTS / 'PANEL-TABS.json'
    tabs = json.loads(tabs_json.read_text())['text'] if tabs_json.exists() else 'the spots in outputs/PANEL-TABS.json'
    (OUT / 'FAB-NOTES.txt').write_text(NOTES.format(
        n_std=sum(1 for v in vias if v.GetDrillValue() >= pcb.FromMM(0.3)),
        n_fan=sum(1 for v in vias if v.GetDrillValue() < pcb.FromMM(0.3)), n_th=n_th,
        unplaced=(', and %s (no clear silk spot)' % ', '.join(unplaced)) if unplaced else '', tabs=tabs,
        notch_w=m.NOTCH_W, notch_d=m.PCB_R - m.NOTCH_Y))
    n = sum(len(l['refs']) for l in lines.values())
    print('fab: gerbers %d files, drill %d files, BOM %d lines / %d parts, CPL %d rows' % (
        len(list((OUT / 'gerbers').iterdir())), len(list((OUT / 'drill').iterdir())), len(lines), n, len(rows)), flush=True)


if __name__ == '__main__':
    main()
    sys.stdout.flush()
    os._exit(0)
